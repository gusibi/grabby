func TestCompareVersions(t *testing.T) {
	cases := []struct {
		a, b string
		want int
	}{
		{"0.8.0", "0.8.0", 0},
		{"v0.8.0", "0.8.0", 0},
		{"0.8.0", "0.7.9", 1},
		{"0.10.0", "0.9.9", 1},
		{"1.0.0", "0.9.9", 1},
		{"0.9.9", "1.0.0", -1},
		{"0.8.0-beta.1", "0.8.0", -1},
		{"0.8.0", "0.8.0-beta.1", 1},
		{"0.8.0-beta.2", "0.8.0-beta.10", -1},
		{"0.8.0-beta", "0.8.0-beta.1", -1},
		{"0.8.0+build.5", "0.8.0", 0},
		{"dev", "0.0.0", 0},
		{"0.8.0", "dev", 1},
	}
	for _, c := range cases {
		if got := CompareVersions(c.a, c.b); got != c.want {
			t.Errorf("CompareVersions(%q, %q) = %d, want %d", c.a, c.b, got, c.want)
		}
	}
}

func TestIsReleaseBuild(t *testing.T) {
	old := Version
	defer func() { Version = old }()

	Version = "dev"
	if IsReleaseBuild() {
		t.Fatal("a source build must not count as a release build")
	}
	if DisplayVersion() != "开发版" {
		t.Fatalf("DisplayVersion() = %q", DisplayVersion())
	}

	Version = "0.9.0"
	if !IsReleaseBuild() {
		t.Fatal("0.9.0 must count as a release build")
	}
	if DisplayVersion() != "0.9.0" {
		t.Fatalf("DisplayVersion() = %q", DisplayVersion())
	}

	Version = "v0.9.0"
	if CurrentVersion() != "0.9.0" {
		t.Fatalf("CurrentVersion() = %q", CurrentVersion())
	}
}

func TestAssetName(t *testing.T) {
	cases := []struct {
		version, goos, goarch string
		want                  string
	}{
		{"0.9.0", "darwin", "arm64", "Grabby-0.9.0-macOS-universal.dmg"},
		{"0.9.0", "darwin", "amd64", "Grabby-0.9.0-macOS-universal.dmg"},
		{"v0.9.0", "windows", "amd64", "Grabby-0.9.0-Windows-amd64.exe"},
		{"0.9.0", "windows", "arm64", "Grabby-0.9.0-Windows-arm64.exe"},
		{"0.9.0", "linux", "amd64", "Grabby-0.9.0-Linux-amd64.tar.gz"},
	}
	for _, c := range cases {
		got, err := AssetName(c.version, c.goos, c.goarch)
		if err != nil {
			t.Fatalf("AssetName(%q, %q, %q): %v", c.version, c.goos, c.goarch, err)
		}
		if got != c.want {
			t.Errorf("AssetName(%q, %q, %q) = %q, want %q", c.version, c.goos, c.goarch, got, c.want)
		}
	}
	if _, err := AssetName("0.9.0", "windows", "386"); err == nil {
		t.Fatal("expected unsupported Windows arch to fail")
	}
}

func TestAssetForPicksPlatformAsset(t *testing.T) {
	rel := &Release{
		TagName: "v0.9.0",
		Assets: []Asset{
			{Name: "checksums.txt"},
			{Name: "Grabby-0.9.0-macOS-universal.dmg"},
			{Name: "Grabby-0.9.0-Windows-amd64-setup.exe"},
			{Name: "Grabby-0.9.0-Windows-amd64.exe"},
			{Name: "Grabby-0.9.0-Linux-amd64.tar.gz"},
		},
	}
	asset, err := rel.AssetFor("windows", "amd64")
	if err != nil {
		t.Fatal(err)
	}
	// The portable exe, never the interactive setup.
	if asset.Name != "Grabby-0.9.0-Windows-amd64.exe" {
		t.Fatalf("got %q", asset.Name)
	}
	if _, err := rel.AssetFor("linux", "arm64"); err == nil {
		t.Fatal("expected a missing arm64 asset to fail")
	}
}

func TestParseChecksums(t *testing.T) {
	raw := []byte(`# generated by the release workflow
9f2c4d8e6a0b1c2d3e4f5a6b7c8d9e0f1a2b3c4d5e6f7a8b9c0d1e2f3a4b5c6d  ./Grabby-0.9.0-macOS-universal.dmg
abc  ./too-short.txt
1f2c4d8e6a0b1c2d3e4f5a6b7c8d9e0f1a2b3c4d5e6f7a8b9c0d1e2f3a4b5c6d *Grabby-0.9.0-Linux-amd64.tar.gz
`)
	sums := parseChecksums(raw)
	if len(sums) != 2 {
		t.Fatalf("got %d checksums, want 2: %#v", len(sums), sums)
	}
	if _, ok := sums["Grabby-0.9.0-macOS-universal.dmg"]; !ok {
		t.Fatalf("missing dmg checksum: %#v", sums)
	}
	if _, ok := sums["Grabby-0.9.0-Linux-amd64.tar.gz"]; !ok {
		t.Fatalf("missing linux checksum: %#v", sums)
	}
}

func TestLatestParsesRelease(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/repos/gusibi/grabby/releases/latest" {
			http.NotFound(w, r)
			return
		}
		if ua := r.Header.Get("User-Agent"); !strings.HasPrefix(ua, "Grabby-Updater/") {
			t.Errorf("unexpected User-Agent %q", ua)
		}
		_ = json.NewEncoder(w).Encode(map[string]any{
			"tag_name": "v0.9.0",
			"html_url": "https://github.com/gusibi/grabby/releases/tag/v0.9.0",
			"assets": []map[string]any{
				{"name": "Grabby-0.9.0-macOS-universal.dmg", "browser_download_url": "https://example.com/x.dmg"},
			},
		})
	}))
	defer srv.Close()

	c := &Client{Base: srv.URL}
	rel, err := c.Latest(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	if rel.Version() != "0.9.0" || !rel.NewerThan("0.8.0") {
		t.Fatalf("unexpected release: %+v", rel)
	}
	if rel.NewerThan("0.9.0") || rel.NewerThan("0.10.0") {
		t.Fatal("release must not be newer than itself or a later version")
	}
}

func TestLatestRejectsHTTPError(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		http.Error(w, "rate limited", http.StatusForbidden)
	}))
	defer srv.Close()

	c := &Client{Base: srv.URL}
	if _, err := c.Latest(context.Background()); err == nil {
		t.Fatal("expected an error on a non-200 response")
	}
}

// TestLiveLatest talks to the real GitHub API. It is skipped unless asked for,
// because the default test run must not depend on the network:
//
//	GRABBY_LIVE_UPDATE_TEST=1 go test ./internal/updater -run TestLiveLatest -v
func TestLiveLatest(t *testing.T) {
	if os.Getenv("GRABBY_LIVE_UPDATE_TEST") == "" {
		t.Skip("set GRABBY_LIVE_UPDATE_TEST=1 to query the GitHub release feed")
	}
	rel, err := New().Latest(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	asset, err := rel.AssetFor(runtime.GOOS, runtime.GOARCH)
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("latest v%s: %s (%d bytes)", rel.Version(), asset.Name, asset.Size)

	// Confirm the asset is actually downloadable before trusting the flow.
	req, err := http.NewRequest(http.MethodHead, asset.BrowserDownloadURL, nil)
	if err != nil {
		t.Fatal(err)
	}
	req.Header.Set("User-Agent", userAgent())
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK && resp.StatusCode != http.StatusFound {
		t.Fatalf("asset HEAD returned %s", resp.Status)
	}
	if _, ok := rel.Asset("checksums.txt"); !ok {
		t.Fatal("release has no checksums.txt")
	}
}

// TestLiveDownloadStages exercises the real download, checksum and staging
// path (mounting the DMG on macOS), without replacing the running app.
func TestLiveDownloadStages(t *testing.T) {
	if os.Getenv("GRABBY_LIVE_UPDATE_TEST") == "" {
		t.Skip("set GRABBY_LIVE_UPDATE_TEST=1 to stage the latest release")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	defer cancel()
	rel, err := New().Latest(ctx)
	if err != nil {
		t.Fatal(err)
	}
	staged, err := New().Download(ctx, rel, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer staged.Close()
	info, err := os.Stat(staged.Path)
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("staged v%s: %s (%d bytes)", staged.Version, staged.Path, info.Size())
	if info.IsDir() && runtime.GOOS == "darwin" {
		plist := filepath.Join(staged.Path, "Contents", "Info.plist")
		if _, err := os.Stat(plist); err != nil {
			t.Fatalf("staged app has no Info.plist: %v", err)
		}
	}
}
